-- --------------------------------------------------------------
-- Generate the ALTER DATABASE AUDIT SPECIFICATION ... ADD statements
-- needed to attach every approved table. Written to a table (not
-- PRINTed — 1,020 tables' worth of DDL would blow past SSMS's PRINT
-- truncation limit) so Jesse/UPH DBA can review the exact DDL before
-- running it (fits the "scripts for review" working model).
-- --------------------------------------------------------------
IF OBJECT_ID('tempdb..#GeneratedDDL') IS NOT NULL DROP TABLE #GeneratedDDL;

DECLARE @ServiceAccountLogin SYSNAME = N'svc_careinsights_clarity';  -- TODO: confirm exact login name
DECLARE @BatchSize INT = 50;  -- ADD clauses per ALTER statement; keeps each
                               -- generated statement a manageable size to
                               -- review/run rather than one 1,020-clause ALTER.

;WITH Numbered AS (
    SELECT SchemaName, TableName,
           ROW_NUMBER() OVER (ORDER BY SchemaName, TableName) AS rn
    FROM dbo.AuditConfig_ApprovedTables
),
Batched AS (
    SELECT *, (rn - 1) / @BatchSize AS BatchNum
    FROM Numbered
)
SELECT
    BatchNum,
    N'
ALTER DATABASE AUDIT SPECIFICATION [DBAuditSpec_CareInsights_SelectActivity]
WITH (STATE = OFF)
' +
    STRING_AGG(
        N'ADD (SELECT ON [' + SchemaName + N'].[' + TableName + N'] BY [' + @ServiceAccountLogin + N'])',
        N',
'
    ) + N';' AS GeneratedStatement
INTO #GeneratedDDL
FROM Batched
GROUP BY BatchNum;

PRINT 'Generated DDL for ' + CAST((SELECT COUNT(*) FROM dbo.AuditConfig_ApprovedTables) AS NVARCHAR(10)) +
      ' tables across ' + CAST((SELECT COUNT(*) FROM #GeneratedDDL) AS NVARCHAR(10)) + ' ALTER statement(s).';
PRINT 'Review with: SELECT BatchNum, GeneratedStatement FROM #GeneratedDDL ORDER BY BatchNum;';
PRINT 'Note: STATE stays OFF in every generated statement — a separate,';
PRINT 'deliberate ALTER ... WITH (STATE = ON) turns the whole thing on once';
PRINT 'both the server audit and all table actions are in place.';

